import express from 'express';
import { createServer } from 'http';
import { GoogleGenAI } from '@google/genai';
import dotenv from 'dotenv';
import path from 'path';
import { fileURLToPath } from 'url';

dotenv.config();

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const app = express();
const server = createServer(app);
const PORT = process.env.PORT ? parseInt(process.env.PORT, 10) : 3000;

app.use(express.json({ limit: '10mb' }));

// Server-side Gemini client with required User-Agent
const apiKey = process.env.GEMINI_API_KEY || '';
const ai = apiKey
  ? new GoogleGenAI({
      apiKey,
      httpOptions: {
        headers: {
          'User-Agent': 'aistudio-build',
        },
      },
    })
  : null;

// Health check endpoint
app.get('/api/health', (_req, res) => {
  res.json({
    status: 'ok',
    service: 'BUILD2FLOW DIGITAL API',
    hasApiKey: Boolean(apiKey),
    timestamp: new Date().toISOString(),
  });
});

// TTS Endpoint using gemini-3.8-flash-tts
app.post('/api/tts', async (req, res) => {
  try {
    const { text, persona } = req.body;
    if (!text) {
      return res.status(400).json({ error: 'Text prompt is required.' });
    }

    if (!ai) {
      // Return simulated fallback audio indicator if API key is not configured in environment
      return res.status(503).json({
        error: 'Gemini API key is not set in environment.',
        fallback: true,
      });
    }

    const voiceName = persona === 'female' ? 'Kore' : 'Zephyr';
    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash-tts',
      contents: [
        {
          role: 'user',
          parts: [
            {
              text: String(text).slice(0, 1000),
              speechMetadata: {
                style: 'Confident, clear Australian digital strategist',
              },
            },
          ],
        },
      ],
      config: {
        responseModalities: ['AUDIO'],
        speechConfig: {
          voiceConfig: {
            prebuiltVoiceConfig: { voiceName },
          },
        },
      },
    });

    const base64Audio =
      response.candidates?.[0]?.content?.parts?.[0]?.inlineData?.data;

    if (!base64Audio) {
      return res.status(500).json({ error: 'No audio generated by model' });
    }

    res.json({
      success: true,
      audioBase64: base64Audio,
      mimeType: 'audio/wav',
    });
  } catch (error: any) {
    console.error('TTS error:', error);
    res.status(500).json({
      error: error.message || 'Failed to synthesize speech',
    });
  }
});

// Google Search Grounding for Live Australian SEO Competitor & Keyword Intel
app.post('/api/seo-audit', async (req, res) => {
  try {
    const { trade, location } = req.body;
    const targetTrade = trade || 'Custom Home Builders';
    const targetLocation = location || 'Sydney, NSW';

    if (!ai) {
      return res.json({
        analysis: `Real-time search grounding requires a configured Gemini API Key. Currently demonstrating simulated intelligence for ${targetTrade} in ${targetLocation}.\n\nKey Local Competitors:\n1. Elite Builders Sydney - Strong Google Maps rating (4.9 stars, 84 reviews)\n2. Sydney Craft Constructions - Highly active Instagram presence and Google local service ads\n3. Eastern Suburbs Luxury Homes - Ranking #1 organically for 'custom architectural builders sydney'\n\nStrategic Recommendations:\n- Build 15 high-authority Australian local citations (YellowPages AU, TrueLocal, Hipages).\n- Acquire 12+ photo reviews showcasing completed luxury renovations.\n- Optimize Google Business Profile service areas for surrounding high-value postcodes.`,
        groundingSources: [
          { title: 'TrueLocal Australia - Top Builders', uri: 'https://www.truelocal.com.au' },
          { title: 'Google Business Directory AU', uri: 'https://www.google.com.au' },
        ],
      });
    }

    const prompt = `You are the lead SEO and Growth Director at BUILD2FLOW DIGITAL, a premier Australian digital marketing agency.
Provide a high-impact, actionable local Google Search & SEO audit for a local business in Australia:
Business Type: ${targetTrade}
Location: ${targetLocation}, Australia

Tasks:
1. Identify the current competitive landscape and search trends in this Australian market.
2. Outline the top 3 critical Google Business Profile and local organic ranking factors to dominate the Local 3-Pack.
3. List 5 high-intent Australian search keywords with estimated competition.
4. Give 3 immediate growth recommendations for BUILD2FLOW DIGITAL to execute.

Keep the response structured, professional, executive-level, and tailored to the Australian market (AEST timezone, Australian terminology like tradie, council DA, quality finishes).`;

    const response = await ai.models.generateContent({
      model: 'gemini-3.5-flash',
      contents: prompt,
      config: {
        tools: [{ googleSearch: {} }],
      },
    });

    const text = response.text || '';
    const groundingChunks =
      response.candidates?.[0]?.groundingMetadata?.groundingChunks || [];

    const sources = groundingChunks
      .map((chunk: any) => chunk.web)
      .filter(Boolean)
      .slice(0, 6);

    res.json({
      analysis: text,
      groundingSources: sources,
    });
  } catch (error: any) {
    console.error('SEO audit error:', error);
    res.status(500).json({
      error: error.message || 'Failed to generate search grounded SEO audit',
    });
  }
});

// AI Growth Advisor endpoint
app.post('/api/ai-advisor', async (req, res) => {
  try {
    const { message, clientContext } = req.body;
    if (!message) {
      return res.status(400).json({ error: 'Message is required' });
    }

    if (!ai) {
      return res.json({
        reply: `Thanks for your enquiry! At BUILD2FLOW DIGITAL, we specialize in high-converting websites, Google Map Pack dominance, and lead automation for Australian trades and builders. For ${clientContext?.businessName || 'your business'}, our Growth system typically delivers a 3.4x return on marketing spend within 90 days. Would you like to review our package options or schedule a 1-on-1 strategy call?`,
      });
    }

    const systemInstruction = `You are Liam, Senior Digital Growth Partner at BUILD2FLOW DIGITAL (Australian Digital Growth Agency).
Tagline: "We Build Your Digital Presence. You Grow Your Business."
Our clients are Australian trades: builders, construction companies, plumbers, electricians, gym owners, cafes, and hospitality venues.
Provide sharp, authoritative, encouraging, commercial advice on websites, Google Business ranking, lead generation, and social media.
Tone: Australian business professional, confident, clear, no fluff.
Client context: ${JSON.stringify(clientContext || {})}`;

    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash',
      contents: message,
      config: {
        systemInstruction,
      },
    });

    res.json({
      reply: response.text || 'We are ready to build your digital presence and grow your business.',
    });
  } catch (error: any) {
    console.error('AI Advisor error:', error);
    res.status(500).json({
      error: error.message || 'AI advisor failed to respond',
    });
  }
});

// In development, hook Vite middleware
async function setupVite() {
  const isProd = process.env.NODE_ENV === 'production';
  if (!isProd) {
    const { createServer: createViteServer } = await import('vite');
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  } else {
    app.use(express.static(path.resolve(__dirname, 'dist')));
    app.get('*', (_req, res) => {
      res.sendFile(path.resolve(__dirname, 'dist', 'index.html'));
    });
  }

  server.listen(PORT, '0.0.0.0', () => {
    console.log(`[BUILD2FLOW DIGITAL] Server running on http://0.0.0.0:${PORT}`);
  });
}

setupVite().catch((err) => {
  console.error('Error starting server:', err);
});
